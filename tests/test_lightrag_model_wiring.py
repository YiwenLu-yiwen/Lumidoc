import pytest

from src.modules.lightraglocal.services.enterprise_lightrag_service import (
    EnterpriseLightRAGService,
)
from src.shared.clients.llm_service_client import LLMServiceClient


@pytest.mark.asyncio
async def test_lightrag_final_answer_calls_the_model(monkeypatch, tmp_path) -> None:
    calls: list[list[dict[str, str]]] = []

    async def fake_chat_generate(self, messages, **kwargs):
        calls.append(messages)
        return "answer generated by the model"

    monkeypatch.setattr(LLMServiceClient, "chat_generate", fake_chat_generate)
    service = EnterpriseLightRAGService(base_storage_dir=str(tmp_path))
    llm_func = service.default_config["llm_model_func"]

    result = await llm_func(
        "Why is the cobalt protocol used?",
        system_prompt="---Knowledge Graph and Document Chunks---\nIt reduces retry storms.",
        history_messages=[],
    )

    assert result == "answer generated by the model"
    assert calls, "the final LightRAG answer must reach the model service"


@pytest.mark.asyncio
async def test_lightrag_embedding_failure_is_not_replaced_by_zero_vectors(
    monkeypatch, tmp_path
) -> None:
    async def failing_embeddings(self, texts):
        raise RuntimeError("model unavailable")

    monkeypatch.setenv("EMBEDDING_DIM", "3")
    monkeypatch.setattr(LLMServiceClient, "get_embeddings", failing_embeddings)
    service = EnterpriseLightRAGService(base_storage_dir=str(tmp_path))
    embedding_func = service.default_config["embedding_func"]

    with pytest.raises(RuntimeError, match="model unavailable"):
        await embedding_func(["hello"])


@pytest.mark.asyncio
async def test_lightrag_rejects_embedding_dimension_mismatch(
    monkeypatch, tmp_path
) -> None:
    async def wrong_dimension(self, texts):
        return [[0.1, 0.2] for _ in texts]

    monkeypatch.setenv("EMBEDDING_DIM", "3")
    monkeypatch.setattr(LLMServiceClient, "get_embeddings", wrong_dimension)
    service = EnterpriseLightRAGService(base_storage_dir=str(tmp_path))
    embedding_func = service.default_config["embedding_func"]

    with pytest.raises(ValueError, match="dimension"):
        await embedding_func(["hello"])
